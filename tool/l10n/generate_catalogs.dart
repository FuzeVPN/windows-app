/// Compile the reviewed JSON catalogs into synchronous, typed Dart constants.
/// Run from the app root. Incomplete catalogs never replace the generated file.
/// --check additionally verifies that the committed output is current.
void main(List<String> args) {
  final check = args.contains('--check');
  final source = readCatalog('source');
  final catalogs = <String, Map<String, String>>{};
  var incomplete = false;
  for (final code in localeCodes) {
    final catalog = readCatalog(code);
    for (final entry in catalog.entries) {
      if (!source.containsKey(entry.key)) {
        throw FormatException('$code: unknown key ${entry.key}');
      }
      if (entry.value.trim().isEmpty) {
        throw FormatException('$code: empty translation for ${entry.key}');
      }
      if (entry.value.contains('\uFFFD')) {
        throw FormatException('$code: invalid Unicode for ${entry.key}');
      }
      if (placeholders(entry.value) != placeholders(source[entry.key]!)) {
        throw FormatException('$code: placeholders differ for ${entry.key}');
      }
    }
    final missing = source.keys
        .where((key) => !catalog.containsKey(key))
        .length;
    if (missing > 0) {
      incomplete = true;
      stderr.writeln('$code: $missing missing translations');
    }
    catalogs[code] = catalog;
  }
  if (incomplete) {
    exitCode = 1;
    return;
  }
  final output = StringBuffer(
    '// Generated by tool/l10n/generate_catalogs.dart. Do not edit.\n\n',
  );
  output.writeln('const sourceCatalog = <String, String>${dartMap(source)};');
  output.writeln(
    '\nconst translationCatalogs = <String, Map<String, String>>{',
  );
  for (final entry in catalogs.entries) {
    output.writeln('  ${quote(entry.key)}: ${dartMap(entry.value)},');
  }
  output.writeln('};');
  final outputs = {
    'lib/l10n/generated_catalogs.dart': output.toString(),
    'windows/runner/generated_native_catalogs.h': nativeCatalogHeader(catalogs),
  };
  for (final entry in outputs.entries) {
    final file = File(entry.key);
    if (check) {
      if (!file.existsSync() || file.readAsStringSync() != entry.value) {
        stderr.writeln('${entry.key} is out of date. Run the generator.');
        exitCode = 1;
      }
    } else {
      file.writeAsStringSync(entry.value);
    }
  }
}

