String nativeCatalogHeader(Map<String, Map<String, String>> catalogs) {
  final output = StringBuffer(
    '// Generated by tool/l10n/generate_catalogs.dart. Do not edit.\n'
    '#ifndef RUNNER_GENERATED_NATIVE_CATALOGS_H_\n'
    '#define RUNNER_GENERATED_NATIVE_CATALOGS_H_\n\n'
    'namespace fuzevpn::l10n {\n'
    'struct NativeCatalog {\n'
    '  const wchar_t* code;\n',
  );
  for (final field in nativeMessageKeys.keys) {
    output.writeln('  const wchar_t* $field;');
  }
  output.writeln('};\n\ninline constexpr NativeCatalog native_catalogs[] = {');
  for (final entry in catalogs.entries) {
    final values = [
      entry.key,
      for (final key in nativeMessageKeys.values) entry.value[key]!,
    ];
    output.writeln('  {${values.map(cppWideString).join(', ')}},');
  }
  output.writeln('};\n}  // namespace fuzevpn::l10n\n\n#endif');
  return output.toString();
}

String cppWideString(String value) {
  final output = StringBuffer('L');
  for (final rune in jsonEncode(value).runes) {
    if (rune <= 0x7f) {
      output.writeCharCode(rune);
    } else {
      final isBasicPlane = rune <= 0xffff;
      output.write(isBasicPlane ? r'\u' : r'\U');
      output.write(rune.toRadixString(16).padLeft(isBasicPlane ? 4 : 8, '0'));
    }
  }
  return output.toString();
}

Map<String, String> readCatalog(String name) {
  final decoded = jsonDecode(
    File('lib/l10n/catalogs/$name.json').readAsStringSync(),
  );
  if (decoded is! Map<String, dynamic> ||
      decoded.values.any((value) => value is! String)) {
    throw FormatException('$name must be a JSON object of string translations');
  }
  return decoded.cast<String, String>();
}

String placeholders(String value) {
  final tokens = RegExp(
    r'\{[A-Za-z_][A-Za-z0-9_]*\}',
  ).allMatches(value).map((m) => m.group(0)!).toList()..sort();
  return tokens.join('|');
}

String quote(String value) => jsonEncode(value).replaceAll(r'$', r'\$');
String dartMap(Map<String, String> entries) {
  final keys = entries.keys.toList()..sort();
  return '{\n${keys.map((key) => '    ${quote(key)}: ${quote(entries[key]!)},').join('\n')}\n  }';
}
